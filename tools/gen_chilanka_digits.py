#!/usr/bin/env python3
"""Regenerates main/chilanka_1300.h - the pre-rendered "1300" bitmap that
hub75/1300L draws (Chilanka-Regular, SIL OFL 1.1).

Renders the string large, crops to its ink bounding box, and scales that box
(non-uniformly - the natural aspect is ~2.65:1, the panel is 2:1) to exactly
fill the WxH panel, so the digits touch all four edges. Anti-aliased
coverage is then converted through the INVERSE of the display library's CIE
1931 lightness curve (cie_luts.h feeds every 8-bit value through
Y = f(L)), so a pixel covering a fraction c of the area comes out with
luminance c rather than being darkened by the library's curve.

  python3 tools/gen_chilanka_1300.py [--crisp] [--no-gamma] [--font PATH]
"""
import argparse
from PIL import Image, ImageDraw, ImageFont

ap = argparse.ArgumentParser()
ap.add_argument("--font", default="/usr/share/fonts/opentype/malayalam/Chilanka-Regular.otf")
ap.add_argument("--width", type=int, default=128)
ap.add_argument("--height", type=int, default=64)
ap.add_argument("--crisp", action="store_true", help="threshold to pure on/off pixels instead of anti-aliasing")
ap.add_argument("--no-gamma", action="store_true", help="skip the inverse-CIE conversion")
ap.add_argument("--out", default="main/chilanka_1300.h")
a = ap.parse_args()
W, H = a.width, a.height

font = ImageFont.truetype(a.font, 600)
big = Image.new("L", (3200, 1200), 0)
ImageDraw.Draw(big).text((100, 100), "1300", font=font, fill=255)
big = big.crop(big.getbbox())
im = big.resize((W, H), Image.LANCZOS)  # linear-coverage domain

def inv_cie(c):  # desired linear luminance fraction -> 8-bit input for lumConvTab
    if c <= 0: return 0
    if c >= 1: return 255
    L = c * 902.3 if c <= 8 / 902.3 else 116 * c ** (1 / 3) - 16
    return max(0, min(255, round(L / 100 * 255)))

px = im.tobytes()
out = []
for v in px:
    if a.crisp:
        out.append(255 if v >= 128 else 0)
    elif a.no_gamma:
        out.append(v)
    else:
        out.append(inv_cie(v / 255.0))

rows = ["    " + ", ".join("0x%02X" % v for v in out[y * W:(y + 1) * W]) + "," for y in range(H)]
mode = "crisp on/off" if a.crisp else ("anti-aliased, linear" if a.no_gamma else "anti-aliased, inverse-CIE gamma")
open(a.out, "w").write(f'''// Generated by tools/gen_chilanka_1300.py from Chilanka-Regular.otf (SIL Open
// Font License 1.1) - do not edit by hand. "1300" stretched to fill the whole
// {W}x{H} panel ({mode}). 0 = background, 255 = full white. Used by
// hub75/1300L. {W * H / 1024:.0f}KB of flash (.rodata), no heap.
#pragma once
#include <stdint.h>

constexpr int kChilanka1300W = {W};
constexpr int kChilanka1300H = {H};
static const uint8_t kChilanka1300[kChilanka1300W * kChilanka1300H] = {{
''' + "\n".join(rows) + "\n};\n")
nz = sum(1 for v in out if v)
print(f"wrote {a.out}: {W}x{H}, {mode}, {nz} lit px ({100*nz/(W*H):.0f}%), max={max(out)}")
for y in range(0, H, 2):
    print("".join(" .:*#"[min(4, out[y * W + x] // 52)] for x in range(0, W, 1)))
